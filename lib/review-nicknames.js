const forbiddenNicknameCharacters = /[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]/u;

/** Normalize presentation only. Nicknames are display names, not unique identities. */
export function normalizeReviewNickname(value) {
  if (typeof value !== 'string') throw new TypeError('昵称必须是文字。');
  // Reject before trimming: a pasted newline or invisible control must not be
  // silently accepted just because it appears at an edge of the input.
  if (forbiddenNicknameCharacters.test(value)) throw new RangeError('昵称不能包含换行、控制字符或不可见字符。');
  const nickname = value.normalize('NFC').trim();
  const length = Array.from(nickname).length;
  if (length < 2 || length > 24) throw new RangeError('昵称需要 2 至 24 个字。');
  return nickname;
}

/** A stable pool selection never embeds an account ID or email in the label. */
export function defaultReviewNickname(userId) {
  let hash = 2166136261;
  for (const character of String(userId ?? '')) {
    hash ^= character.codePointAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return REVIEW_NICKNAMES[(hash >>> 0) % REVIEW_NICKNAMES.length];
}

function randomIndex(size) {
  const crypto = globalThis.crypto;
  if (!crypto || typeof crypto.getRandomValues !== 'function') throw new Error('暂时无法生成随机昵称，请手动填写昵称。');
  const limit = Math.floor(0x100000000 / size) * size;
  const bytes = new Uint32Array(1);
  // Rejection sampling avoids bias when the pool size does not divide 2^32.
  do { crypto.getRandomValues(bytes); } while (bytes[0] >= limit);
  return bytes[0] % size;
}

/** Supports both randomReviewNickname(previous) and ({ previous }). */
export function randomReviewNickname(options = '') {
  const value = options && typeof options === 'object' ? options.previous : options;
  const previous = typeof value === 'string' ? value.normalize('NFC').trim() : '';
  const excluded = REVIEW_NICKNAMES.indexOf(previous);
  const index = randomIndex(REVIEW_NICKNAMES.length - (excluded >= 0 ? 1 : 0));
  return REVIEW_NICKNAMES[excluded >= 0 && index >= excluded ? index + 1 : index];
}
